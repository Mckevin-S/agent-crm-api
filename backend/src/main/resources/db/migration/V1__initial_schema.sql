-- Comptes des conseillers et managers
CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    email         VARCHAR(160) NOT NULL,
    full_name     VARCHAR(80)  NOT NULL,
    password_hash VARCHAR(100) NOT NULL,
    role          VARCHAR(10)  NOT NULL CHECK (role IN ('AGENT', 'MANAGER'))
);
CREATE UNIQUE INDEX ux_app_user_email ON app_user (LOWER(email));

-- Répartition des clients du CRM entre conseillers
CREATE TABLE portfolio_assignment (
    customer_id VARCHAR(10) PRIMARY KEY,
    agent_id    BIGINT NOT NULL REFERENCES app_user (id)
);
CREATE INDEX ix_portfolio_agent ON portfolio_assignment (agent_id);

-- Échanges avec les clients
CREATE TABLE interaction (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id VARCHAR(10)   NOT NULL,
    agent_id    BIGINT        NOT NULL REFERENCES app_user (id),
    agent_name  VARCHAR(80)   NOT NULL,
    channel     VARCHAR(10)   NOT NULL,
    direction   VARCHAR(10)   NOT NULL,
    subject     VARCHAR(120)  NOT NULL,
    notes       VARCHAR(2000),
    occurred_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_interaction_customer ON interaction (customer_id, occurred_at DESC);
CREATE INDEX ix_interaction_agent ON interaction (agent_id, occurred_at);

-- Tâches de suivi
CREATE TABLE follow_up_task (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id         VARCHAR(10)  NOT NULL,
    assignee_id         BIGINT       NOT NULL REFERENCES app_user (id),
    title               VARCHAR(160) NOT NULL,
    notes               VARCHAR(2000),
    priority            VARCHAR(10)  NOT NULL,
    due_date            DATE         NOT NULL,
    status              VARCHAR(10)  NOT NULL,
    recommendation_code VARCHAR(30),
    recommendation_ref  VARCHAR(30),
    created_at          TIMESTAMP WITH TIME ZONE NOT NULL,
    completed_at        TIMESTAMP WITH TIME ZONE
);
CREATE INDEX ix_task_assignee_status ON follow_up_task (assignee_id, status);
CREATE INDEX ix_task_customer ON follow_up_task (customer_id);

-- Recommandations écartées
CREATE TABLE recommendation_dismissal (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    customer_id  VARCHAR(10)  NOT NULL,
    code         VARCHAR(30)  NOT NULL,
    reference    VARCHAR(30)  NOT NULL,
    agent_id     BIGINT       NOT NULL REFERENCES app_user (id),
    reason       VARCHAR(300) NOT NULL,
    dismissed_at TIMESTAMP WITH TIME ZONE NOT NULL
);
CREATE INDEX ix_dismissal_customer ON recommendation_dismissal (customer_id);

-- Dernière copie connue des profils CRM (mode dégradé)
CREATE TABLE customer_snapshot (
    customer_id  VARCHAR(10) PRIMARY KEY,
    display_name VARCHAR(160) NOT NULL,
    search_text  VARCHAR(400) NOT NULL,
    payload      TEXT         NOT NULL,
    fetched_at   TIMESTAMP WITH TIME ZONE NOT NULL
);
